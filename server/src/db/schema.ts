/** Money stored as decimal(12,2), exposed to TypeScript as a number. */
const money = customType<{ data: number; driverData: string }>({
  dataType: () => 'decimal(12, 2)',
  fromDriver: (v) => Number(v),
  toDriver: (v) => String(v),
});

// Times are stored as UTC datetime(3); the connection runs in UTC (see db/client.ts).
const ts = (name: string) => datetime(name, { mode: 'date', fsp: 3 });
const now = sql`CURRENT_TIMESTAMP(3)`;
/** UUID text ids, generated by the app (MySQL has no built-in UUID default that works everywhere). */
const uuid = (name: string) => varchar(name, { length: 36 });
const id = () => uuid('id').primaryKey().$defaultFn(() => randomUUID());
const createdAt = () => ts('created_at').notNull().default(now);
/**
 * JSON column. MySQL hands JSON back already parsed; MariaDB stores JSON as text and hands back a string,
 * so parse whenever it's a string. Works on both.
 */
const json = customType<{ data: unknown; driverData: string }>({
  dataType: () => 'json',
  toDriver: (v) => JSON.stringify(v),
  fromDriver: (v) => (typeof v === 'string' ? JSON.parse(v) : v),
});
/** JSON column whose default is applied by the app (MySQL can't default JSON columns portably). */
const jsonOf = <T>(name: string, def: () => T) => json(name).$type<T>().notNull().$defaultFn(def);

